const LANGS = ['en', 'nb'];

// The language: the visitor's choice (kept in the browser), else the browser's language, else English.
function pickLang() {
  let saved = '';
  try { saved = localStorage.getItem('tp.lang') || ''; } catch (e) { /* private mode */ }
  if (LANGS.includes(saved)) return saved;
  const prefs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || '']);
  for (const p of prefs) {
    const base = String(p).toLowerCase().split('-')[0];
    if (base === 'nb' || base === 'nn' || base === 'no') return 'nb';
    if (base === 'en') return 'en';
  }
  return 'en';
}

let currentLang = pickLang();
function setLang(l) {
  currentLang = LANGS.includes(l) ? l : 'en';
  try { localStorage.setItem('tp.lang', currentLang); } catch (e) { /* private mode */ }
  document.documentElement.lang = currentLang === 'nb' ? 'nb' : 'en';
}
document.documentElement.lang = currentLang === 'nb' ? 'nb' : 'en';

const hasMsg = (key) => key in MESSAGES[currentLang] || key in MESSAGES.en;

// t('key', {name: 'x'}) fills {name}. A missing key falls back to English, then to the key itself.
function t(key, params) {
  const msg = MESSAGES[currentLang][key] ?? MESSAGES.en[key] ?? key;
  return params ? msg.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : msg;
}
// tn('key', n, params): key.one when n is 1, else key.other; {n} is filled in.
function tn(key, n, params) {
  return t(key + (n === 1 ? '.one' : '.other'), { n, ...params });
}
